export const signatureById=id=>SIGNATURE_PARTS.find(p=>p.id===id)||null;
export const isSignature=p=>Number.isInteger(p?.car)&&!!p?.signature;
// На какой машине деталь работает: именная — только на своей, остальные — на любой.
export const partFitsCar=(p,car)=>!isSignature(p)||p.car===car;
export const signaturesOf=car=>SIGNATURE_PARTS.filter(p=>p.car===car);
// Тяга. Разгон в физике — (тяга − скорость × сопротивление) × мощь: мощь умножает всю скобку, но
// предельная скорость — это тяга, делённая на сопротивление, и мощью её не поднять. У Копейки самый
// тупой кузов в парке (0.078), поэтому на 804 м она упиралась в 260 км/ч при любом моторе. Именный
// мотор поднимает саму тягу — с ним машина не только быстрее разгоняется, но и дальше едет.
export function signatureAccel(s,car=s?.selected){
 const id=s?.equipped?.[car]?.engine,p=signatureById(id);
 return p&&p.car===car&&s.inventory?.[id]?(p.accel||1):1;
}
// Сколько ступеней добавляет именная КПП, стоящая на этой машине.
export function signatureGears(s,car=s?.selected){
 const id=s?.equipped?.[car]?.gearbox,p=signatureById(id);
 return p&&p.car===car&&s.inventory?.[id]?(p.gears||0):0;
}
