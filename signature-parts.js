// Именные детали (Андрей, 9 октября): уникальные технические части под конкретную машину. Мотор, КПП
// и шины — по тройке на каждую машину лестницы. Они «очень круто смотрятся и дают лютый приток мощи»:
// именная деталь — это не ещё одна строчка в списке, а повод вернуться к машине, которую давно поставил
// во двор. Копейка с «Арканом» и «Семиступкой» снова дерёт и Восьмёрку, и всё остальное.
//
// Три правила делают такую деталь событием:
//   car     — встаёт только на свою машину и только на ней работает. Переложить ротор на Волгу нельзя.
//   потолок — проходит сквозь потолок кузова (BODY_RANK). Потолок говорит «этот кузов больше не держит»,
//             именная деталь — то самое исключение. Её ранг считается по ней самой, до 15.
//   power   — множитель к характеристике слота. Обычная легендарка даёт 1, именная — заметно больше.
// У КПП ещё gears — сколько ступеней она добавляет сверх заводских. «Семиступка» на Копейке: 4 + 3.
//
// Модуль без зависимостей: его читают и прогрессия, и апгрейды (raceKit), и сервер (trust.js) —
// так они не замыкаются друг на друга.
//
// Добываются как всё уникальное: красный ящик (боссы последних районов, рубеж корешей, 900 $).
// В витрину за рубли не попадают никогда.

const ENGINE=[1,0,0],TIRES=[0,1,0],GEARBOX=[0,0,1];
const sig=(slot,car,key,nickname,power,note,extra={})=>({
 id:slot+'-sig-'+key,slot,car,signature:key,style:null,styleName:null,variant:0,tag:null,bias:null,
 name:{engine:'Мотор',tires:'Шины',gearbox:'КПП'}[slot]+' «'+nickname+'»',nickname,rarity:4,maxRank:15,
 icon:{engine:'⚙',tires:'◉',gearbox:'⤴'}[slot],stats:{engine:ENGINE,tires:TIRES,gearbox:GEARBOX}[slot].map(v=>v*power),
 power,note,...extra,
});

