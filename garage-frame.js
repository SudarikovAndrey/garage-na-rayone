// Кадр гаража под форму экрана.
//
// Камера бокса — ортографическая, и раньше её ширина задавалась только длиной машины: по горизонтали
// всегда ровно span, по вертикали — span*h/w. На телефоне это давало высокий кадр, где виден весь бокс.
// На широком экране (полный экран с компьютера) та же формула резала кадр по высоте, и от гаража
// оставалась одна машина крупным планом — Андрей, 8 октября: «не видно гараж вообще, нужно отдалиться».
//
// Теперь ширину подбираем так, чтобы по вертикали кадр был не ниже MIN_VIEW·span: на узких экранах
// формула прежняя, на широких камера отъезжает. Отъезд упирается в MAX_VIEW — полуширину бокса:
// дальше в кадр лезет только темнота за стенами.
export const GARAGE_MIN_VIEW=1,GARAGE_MAX_VIEW=5.2;
export function garageFrame(span,aspect){
 const wide=span*GARAGE_MIN_VIEW*aspect;
 const halfW=Math.min(Math.max(span,GARAGE_MAX_VIEW),Math.max(span,wide));
 return {halfW,halfH:halfW/aspect};
}
