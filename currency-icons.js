// Иконки валют. Три ресурса игры различаются силуэтом, а не цветом: на телефоне цвет тонет в
// подсветке кадра, а пятно читается всегда. Поэтому рисуем одним заполнением, без обводок и
// внутренних линий — знак либо вырезан в пятне, либо это сам контур предмета.
//
//   soft  — монеты: диск с вырезанным ₽;
//   hard  — кристаллы: огранённый камень;
//   parts — запчасти: шестерня;
//   power — мощь машины: молния (не ресурс, но живёт тем же значком рядом с числом).
//
// Одного размера, в одну строку с цифрой и одним шрифтом: ресурсы равны по значимости, и подписи
// им не нужны. Цвета вынесены в CSS (`.coin` в ui-surfaces.css), чтобы состояния («не хватает»)
// меняли только цвет, не разметку.
