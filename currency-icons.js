  'M12 8.7A3.3 3.3 0 1 0 12 15.3A3.3 3.3 0 1 0 12 8.7Z"/></svg>',
 // Мощь — молния. Тот же силуэт рисует пригласительная карточка на канвасе (invite-card.js),
 // чтобы значок мощи был один и тот же и в игре, и на картинке для друга.
